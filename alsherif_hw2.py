"""#Problem 5- GD with Backtracking Line Search

##Task 1- Fixed c
"""

tolerance = 1e-10 #tolerance if ||g|| drops to this you are at the bottom so stop
num_iterations = 30 #iterate 30 times, max number of updates per the brief
G = A.T@A #precompute G, per the brief
v = A.T@y #precompute v, per the brief
beta_values = [0.1, 0.2, 0.5, 0.9] # beta values given by the brief
c = 0.1 # given by the brief, the strictness of the step drop
bls_results = {}

for b in beta_values: #beta run
  execution_times = []
  for timer_iter in range(6):
    start_time = time.perf_counter() # Start the timer

    x = x_init.copy() #every run starts at x_0
    L_values = [] #a place to put all the L values at each update
    gammas = [] #store all the gamma values at each update
    iterates = [] #store x_n at each update
    n_updates = 0
    reduction_counter = 0
    evaluation_counter = 1
    current_loss = np.linalg.norm(A@x - y)**2

    for i in range(num_iterations): #GD update loop before the search is performed
      g = 2*(G@x - v) #gradient at which you are standing at before the search
      if np.linalg.norm(g) <= tolerance:
        break

      g_norm_sq = np.linalg.norm(g)**2

      # Backtracking Line Search
      gamma = 1.0
      for search_iter in range(100):
        x_trial = x - gamma * g
        trial_loss = np.linalg.norm(A@x_trial - y)**2
        evaluation_counter += 1
        if trial_loss <= current_loss - c * gamma * g_norm_sq:
          break
        gamma = b * gamma
        reduction_counter += 1
      else:
        print("Backtracking line search failed to converge")
        break

      x = x - gamma * g
      n_updates = n_updates + 1
      current_loss = trial_loss
      L_values.append(trial_loss)
      iterates.append(x)
      gammas.append(gamma)

    end_time = time.perf_counter() # Stop the timer
    elapsed = end_time - start_time
    if timer_iter > 0:
      execution_times.append(elapsed)

  # Compute median or record times
  median_time = np.median(execution_times)

  while len(gammas) < num_iterations:
    gammas.append(np.nan)
  while len(L_values) < num_iterations:
    L_values.append(L_values[-1])

  bls_results[b]= {"L":L_values, "gammas":gammas, "reduction":reduction_counter, "eval":evaluation_counter, "times": execution_times, "median times": median_time}

  print(f"beta:{b}", f"n_updates: {n_updates}")
  print(f"execution times over five rounds: {execution_times}s")
  print(f"Median execution time (over 6 runs): {median_time:.6f} seconds")
  print(f"gap: {L_values[-1] - lopt}")
  print(f"distance to xopt: {np.linalg.norm(iterates[-1] - xopt)}")
  print(f"reduction counter: {reduction_counter}")
  print(f"evaluation counter: {evaluation_counter}\n")

