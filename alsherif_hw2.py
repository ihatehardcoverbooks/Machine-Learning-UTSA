"""#Load Data"""

# Problem 0: load A, y, and xinit (space-separated values, no header) as float64
A = np.loadtxt("A.csv", dtype=np.float64)                  # A is N x K
y = np.loadtxt("y.csv", dtype=np.float64).ravel()          # y is length N
x_init = np.loadtxt("x_init.csv", dtype=np.float64).ravel()  # xinit is length K

N, K = A.shape  # N rows (data points), K columns (unknowns)
print("A:", A.shape, " y:", y.shape, " x_init:", x_init.shape)

"""#Problem 2

##Calculate H
"""

#Calculate H

#H = 2A^TA

H = 2*A.T@A
print(f"H shape: {H.shape}")

"""##Calculate C"""

#Calculate C

#C = 2sigmamax(A)^2

largest_values = np.linalg.svd(A, compute_uv=False)

largest_value = max(largest_values)

C = 2*largest_value**2
print(f"C:{C}")

#check to see if C is correct, should equal largest value of H

sigmas_of_H = np.linalg.svd(H, compute_uv=False)
largest_of_H = max(sigmas_of_H)
print(f"largest value of H: {largest_of_H}")

#They match!

"""## rank, xopt and lopt"""

#rank reduced SVD of A

U,s,Vt = np.linalg.svd(A,full_matrices = False)
print(f"shape of U:{U.shape}")
print(f"shape of s:{s.shape}")
print(f"shape of Vt:{Vt.shape}")

#calculate tolerance, so that we can eliminate the near zero values

N, K = A.shape
eps = np.finfo(A.dtype).eps
max_dim = max(N, K)
sigma_1 = s[0]
tol = max_dim * sigma_1 * eps
print(f"tolerance: {tol}")

#calculate rank

rank = np.sum(s > tol)
print(f"rank: {rank}")

#calculate xopt
xopt = Vt.T@(U.T@y/s)
print(f"xopt shape: {xopt.shape}")
print(f"xopt:{xopt}")

#calculate lopt
lopt = np.linalg.norm(A@xopt-y)**2
print(f"lopt: {lopt}")

"""#Problem 3- GD with Fixed Step Size"""

tolerance = 1e-10 #tolerance
num_interations = 30 #iterate 30 times
G = A.T@A #precompute G
v = A.T@y #precompute v

p_values= [0.1, 0.5, 1, 1.5, 2]
fss_results = {}

for p in p_values:
  execution_times = []

  for timer_iter in range(6):
    start_time = time.perf_counter() # Start the timer
    gamma = p/C #fixed step size
    iterates= []
    n_updates = 0
    x = x_init.copy() #start at x_0

    for i in range(num_interations): #loop
      g = 2*(G@x -v) #GD for LS, which way is uphill from where i am right now?

      if np.linalg.norm(g)<= tolerance:
        break

      x = x - gamma*g #GD- take one step downhill, new x replaces old x
      n_updates = n_updates + 1
      iterates.append(x)

    end_time = time.perf_counter() # Stop the timer
    elapsed = end_time - start_time
    if timer_iter > 0:
      execution_times.append(elapsed)

  L_values=[] #a place to put all the L values to print at the end
  for i in range(len(iterates)):
    L_values.append(np.linalg.norm(A@iterates[i]-y)**2) #how wrong/ far Ax is from y

  while len(L_values)<num_interations:
    L_values.append(L_values[-1])

  # Compute median or record times
  median_time = np.median(execution_times)

  fss_results[p] = {"L":L_values, "n_updates":n_updates, "times": execution_times, "median times": median_time}

  print(f"p:{p}", f"n_updates: {n_updates}")
  print(f"firstL: {L_values[0]}")
  print(f"lastL: {L_values[-1]}")
  print(f"gap: {L_values[-1]- lopt}")
  print(f"distance to xopt: {np.linalg.norm(iterates[-1]-xopt)}")
  print(f"number of updates: {n_updates}")
  print(f"number of iterations: {len(L_values)}")
  print(f"execution times over five rounds: {execution_times}s")
  print(f"Median execution time (over 5 runs): {median_time:.6f} seconds\n")

"""Plot"""

plt.figure(figsize=(8,5))

for p in p_values:
    plt.plot(range(1,31), fss_results[p]["L"], label=f"p={p}")

plt.axhline(y=lopt, color='black',linestyle='--', label='Lopt')

plt.xlabel('number of iterations')
plt.ylabel('L values')
plt.title('GD with Fixed Step Size for p ∈ {0.1, 0.5, 1, 1.5, 2}')
plt.legend()
plt.yscale('log')
plt.show()

"""#Problem 4- GD with Exact Line Search"""

tolerance = 1e-10 #tolerance
num_interations = 30 #iterate 30 times
G = A.T@A #precompute G
v = A.T@y #precompute v

execution_times = []

for timer_iter in range(6):
  start_time = time.perf_counter() # Start the timer
  x = x_init.copy() #start at x_0
  iterates = []
  gammas_els = []
  n_updates = 0

  for i in range(num_interations): # GD loop
    g = 2*(G@x - v) #GD for LS, which way is uphill from where i am right now?
    if np.linalg.norm(g) <= tolerance:
      break
    gamma = (np.linalg.norm(g)**2)/(2*(np.linalg.norm(A@g)**2)) #γₙ = ‖gₙ₋₁‖₂² / (2‖A gₙ₋₁‖₂²), dynamically changing/adjusting step size
    x = x - gamma*g #GD- take one step downhill, new x replaces old x
    n_updates = n_updates + 1
    gammas_els.append(gamma)
    iterates.append(x)

  end_time = time.perf_counter() # Stop the timer
  elapsed = end_time - start_time
  if timer_iter > 0:
    execution_times.append(elapsed)

# diagnostic only: computed after timing, from the saved iterates
L_els = []
for i in range(len(iterates)):
  L_els.append(np.linalg.norm(A@iterates[i] - y)**2) #how wrong/ far Ax is from y

while len(L_els) < num_interations:
  L_els.append(L_els[-1])

median_time = np.median(execution_times)

els_results = {"L": L_els, "gammas": gammas_els, "n_updates": n_updates, "times": execution_times, "median times": median_time}

print(f"n_updates: {n_updates}")
print(f"firstL: {L_els[0]}")
